//! # Reshaping an empty tensor to add a unit axis panics.
//!
//! ## Expected semantics
//!
//! A tensor of shape `[0]` holds no elements, and so does one of shape
//! `[1, 0]`: `reshape([1, 0])`, `unsqueeze()` and `unsqueeze_dims(&[0])` should
//! each give a `[1, 0]` tensor, as `PyTorch`'s `reshape(1, 0)` and
//! `unsqueeze(0)` do.
//!
//! ## The defect
//!
//! Each panics, with `index out of bounds: the len is 1 but the index is 1`,
//! from `cubecl-zspace`'s `Shape::reshape`, which reads a `0` in the target
//! shape as "copy this input dimension" and finds no second input dimension
//! to copy.
//!
//! ## Why it matters
//!
//! A zero-length sequence is an ordinary state for a streaming cache before
//! it fills: a speaker cache and its FIFO are empty at a stream's first step.
//! A graph that concatenates them with the chunk, generated by `burn-onnx`,
//! hits the reshape on that step (the `Nemotron-3-Diarization` reference in
//! `bind-sortformer-onnx` cannot run its first step).
//!
//! ## Recovery
//!
//! bunsen's Sortformer `SpeakerCache` and streams hold an empty part as
//! `None`, never as a zero-length tensor, so they never reach the reshape;
//! the validation crate's reference tests give the generated graph non-empty
//! caches. Neither changes once the defect is fixed.

#[cfg(test)]
mod tests {
    use bunsen::support::testing::{
        cpu_device,
        performance_device,
    };
    use burn::{
        prelude::*,
        tensor::Int,
    };

    fn reshapes(device: &Device) -> Vec<(&'static str, std::thread::Result<[usize; 2]>)> {
        let empty = || Tensor::<1, Int>::arange(0..0, device);
        vec![
            (
                "reshape([1, 0])",
                std::panic::catch_unwind(|| empty().reshape([1, 0]).dims()),
            ),
            (
                "unsqueeze()",
                std::panic::catch_unwind(|| empty().unsqueeze::<2>().dims()),
            ),
            (
                "unsqueeze_dims(&[0])",
                std::panic::catch_unwind(|| empty().unsqueeze_dims::<2>(&[0]).dims()),
            ),
        ]
    }

    /// The reproduction: an empty tensor gains a unit axis.
    #[test]
    #[ignore = "burn defect: reshaping [0] to [1, 0] panics; see the module docs"]
    fn test_empty_tensor_gains_a_unit_axis() {
        for device in [cpu_device(), performance_device()] {
            for (what, result) in reshapes(&device) {
                assert_eq!(result.expect(what), [1, 0], "{what}");
            }
        }
    }

    /// The behaviour pin: each reshape panics today.
    #[test]
    fn test_pin_empty_reshape_panics() {
        for device in [cpu_device(), performance_device()] {
            for (what, result) in reshapes(&device) {
                assert!(
                    result.is_err(),
                    "{what} no longer panics on {device:?}: the empty-reshape defect is fixed. \
                     Un-ignore `test_empty_tensor_gains_a_unit_axis`; bunsen's `None`-for-empty \
                     parts in the Sortformer cache can stay, and the sortformer validation's \
                     reference tests may then also cover a first, empty-cache step."
                );
            }
        }
    }
}
