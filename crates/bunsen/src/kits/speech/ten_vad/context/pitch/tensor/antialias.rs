//! # The anti-alias filter, in two tensor formulations.
//!
//! The reference decimates 16 kHz to 4 kHz, and guards the new Nyquist with a
//! five-section Direct-Form-II IIR cascade. This is the one part of the pitch
//! estimator with two genuinely different tensor formulations, so it is where
//! the reference and optimized tiers diverge — every other stage has a single
//! natural translation.
//!
//! ```text
//! [batch, steps·hop]  ->  [batch, steps·hop/4]
//! ```
//!
//! ## [`PitchAntiAliasConfig::Recurrence`] — the reference tier
//!
//! The cascade transcribed literally: five sections, each stepping sample by
//! sample through `w0 = x − a₁w₁ − a₂w₂`. Batched across streams but **not**
//! across samples — the recurrence forbids it — so it costs `5 × samples`
//! sequential steps. At 256 samples per hop that is 1280 steps per hop, which
//! is fine for a short equivalence check and hopeless for a real workload.
//!
//! It exists to answer one question the optimized tier cannot: *was the
//! algorithm translated correctly?* Comparing only against the host would
//! conflate a translation error with the deliberate approximation below.
//!
//! ## [`PitchAntiAliasConfig::TruncatedFir`] — the default
//!
//! The same LTI system realized as a truncated impulse response, with the ×4
//! decimation folded into the kernel, evaluated as one GEMM:
//!
//! ```text
//! y[m] = Σ_{k<taps} h[k]·u[4m − k]
//! ```
//!
//! `h` is generated by running a unit impulse through the exact host
//! [`BiquadCascade`], so truncation is the *only* difference between the two
//! tiers.
//!
//! **This is not a speed-for-accuracy trade.** Measured against an `f64`
//! ground truth, the truncated FIR is 25-50% *more* accurate than the host's
//! own `f32` DF-II cascade (7.3e-7 vs 1.5e-6 relative on full-scale input),
//! because it is a better-conditioned realization of the same filter rather
//! than an approximation of it. At the default 2048 taps the truncation
//! contributes ~8e-11 — three orders of magnitude below the `f32` noise floor
//! of the thing it replaces.
//!
//! ### Why it is a GEMM and not a `conv1d`
//!
//! `burn-flex`'s depthwise convolution path fires exactly when
//! `channels == groups == 1`, and parallelizes over `batch × channels` — which
//! is then *one* task. A 2048-tap convolution over a long stream would run
//! single-threaded. Reshaping the windows and contracting against a constant
//! `[in_len, hop/4]` matrix hits a threaded, vectorized GEMM instead.
//!
//! ### Geometry
//!
//! Output `m` of a hop reads `u[4m − k]` for `k < taps`, so a window must span
//! from `taps − 1` samples before the hop to `4·(hop/4 − 1) + 1` after it:
//!
//! ```text
//! in_len = hop + taps − 4          carry = taps − 1
//! T[j, m] = h[(4m + carry) − j]    for 0 ≤ 4m + carry − j < taps
//! ```
//!
//! The carry is `taps − 1`, **not** `in_len − hop`. Those differ by three, and
//! using the latter would both drop the three oldest taps and desync the carry
//! from the kernel offset. Both are derived from one constant here, and
//! `test_fir_matches_the_exact_cascade` would catch a slip.

