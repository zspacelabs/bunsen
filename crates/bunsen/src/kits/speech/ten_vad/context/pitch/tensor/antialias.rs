    #[test]
    fn test_batch_row_offset_regression() {
        // The bug the trim fixes, at the real geometry: before it, row 1's
        // output was garbage while row 0 was bit-exact. The upstream behaviour
        // itself is pinned by `burner::tensor::burn_behavior`.
        let device = Default::default();
        let cfg = PitchAntiAliasConfig::default();
        let filter = cfg.init::<B>(HOP, &device);

        let a = signal(2 * HOP);
        let b: Vec<f32> = a.iter().map(|v| -0.5 * v).collect();

        let mut flat = a.clone();
        flat.extend_from_slice(&b);
        let batched = Tensor::<B, 2>::from_data(TensorData::new(flat, [2, 2 * HOP]), &device);
        let (out, _) = filter.forward(batched, filter.init_state(2, &device));
        let got: Vec<f32> = out.to_data_as::<f32>().to_vec_as::<f32>().unwrap();

        // The filter is linear, so row 1 must be exactly -0.5x row 0.
        let per = got.len() / 2;
        let peak = got[..per].iter().fold(0.0f32, |m, v| m.max(v.abs()));
        for i in 0..per {
            let want = -0.5 * got[i];
            assert!(
                (got[per + i] - want).abs() / peak < 1e-6,
                "row 1 sample {i}: {} vs {want}",
                got[per + i],
            );
        }
    }
