//! The whole catalog: the sources in manifest order, each layer built (or
//! taken from the build cache), checked as one stack, and written as a
//! catalog directory.
//!
//! A catalog directory is a `MANIFEST.txt` and its layer files. The
//! manifest lists the layers in import order, one per line, each with an
//! optional bunsen feature the layer needs (`qwen3.yml kits`); `#` starts a
//! comment. The sources' manifest, `probe_contracts/MANIFEST.txt`, has the
//! same form, and its first layer is the base catalog.

use std::{
    fs,
    path::{
        Path,
        PathBuf,
    },
};

use bunsen::{
    data::catalog::{
        BunsenCatalog,
        BunsenCatalogStack,
        CatalogErrorExt,
        document::OrderedNode,
    },
    kits::support::catalog_contracts::{
        contracts_section,
        kit_catalog_contracts,
    },
};

use crate::{
    layer::LayerBuilder,
    remote::{
        Remote,
        sha256_of,
    },
};

/// The version of what the builder writes: part of each layer's cache key,
/// so a builder that writes differently builds every layer again.
pub const TOOL_STAMP: &str = concat!(env!("CARGO_PKG_VERSION"), "/catalog-builder-1");

/// The manifest's file name, in a catalog directory and among the sources.
pub const MANIFEST: &str = "MANIFEST.txt";

/// One line of a manifest: a layer file, and the feature it needs.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ManifestEntry {
    /// The layer's file name (`qwen3.yml`).
    pub file: String,

    /// The bunsen feature the layer needs, when it needs one.
    pub feature: Option<String>,
}

impl ManifestEntry {
    /// The layer's name: its file name without the extension.
    pub fn name(&self) -> &str {
        self.file
            .rsplit_once('.')
            .map_or(self.file.as_str(), |(stem, _)| stem)
    }
}

/// The entries `text` lists.
///
/// # Errors
/// A line of more than a file and a feature, a file listed twice, or no
/// layers at all.
pub fn parse_manifest(text: &str) -> Result<Vec<ManifestEntry>, String> {
    let mut entries: Vec<ManifestEntry> = Vec::new();
    for (n, line) in text.lines().enumerate() {
        let line = line.split('#').next().unwrap_or_default().trim();
        if line.is_empty() {
            continue;
        }
        let words: Vec<&str> = line.split_whitespace().collect();
        let (file, feature) = match words.as_slice() {
            [file] => (*file, None),
            [file, feature] => (*file, Some(feature.to_string())),
            _ => {
                return Err(format!(
                    "line {}: a manifest line is a file and an optional feature",
                    n + 1
                ));
            }
        };
        if entries.iter().any(|e| e.file == file) {
            return Err(format!("line {}: {file} is listed twice", n + 1));
        }
        entries.push(ManifestEntry {
            file: file.to_string(),
            feature,
        });
    }
    if entries.is_empty() {
        return Err("the manifest lists no layers".into());
    }
    Ok(entries)
}

/// `entries` as a manifest.
pub fn render_manifest(entries: &[ManifestEntry]) -> String {
    let mut text = String::from(
        "# The built-in catalog's layers, in import order, each with the bunsen feature it\n\
         # needs. Generated by `cargo catalog update`, from\n\
         # validation/catalog_builder/probe_contracts/; don't edit by hand.\n",
    );
    for entry in entries {
        match &entry.feature {
            Some(feature) => text.push_str(&format!("{} {feature}\n", entry.file)),
            None => text.push_str(&format!("{}\n", entry.file)),
        }
    }
    text
}

/// A built catalog: its manifest and its layer files, by file name.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct BuiltCatalog {
    /// The layers, in import order.
    pub manifest: Vec<ManifestEntry>,

    /// Each layer's text, in manifest order.
    pub layers: Vec<String>,
}

impl BuiltCatalog {
    /// The directory's files: the manifest, then the layers.
    pub fn files(&self) -> Vec<(String, String)> {
        let mut files = vec![(MANIFEST.to_string(), render_manifest(&self.manifest))];
        files.extend(
            self.manifest
                .iter()
                .zip(&self.layers)
                .map(|(e, text)| (e.file.clone(), text.clone())),
        );
        files
    }
}

/// Where the builder reads and writes.
#[derive(Clone, Debug)]
pub struct Paths {
    /// The probe-contract sources: `probe_contracts/`.
    pub sources: PathBuf,

    /// The build cache and the built directory: the validation workspace's
    /// `target/catalog-builder/`.
    pub target: PathBuf,

    /// The checked-in catalog: `crates/public/bunsen-catalog/catalog/`.
    pub checked_in: PathBuf,

    /// The repository's YAML style, `.ryl.toml`: the built layers are written
    /// as `ryl format` writes them; as the builder writes them, when `None`.
    pub yaml_style: Option<PathBuf>,
}

impl Paths {
    /// The builder's paths in this checkout.
    pub fn of_checkout() -> Self {
        let crate_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        let validation = crate_dir.join("..");
        Self {
            sources: crate_dir.join("probe_contracts"),
            target: validation.join("target").join("catalog-builder"),
            checked_in: validation
                .join("..")
                .join("crates")
                .join("public")
                .join("bunsen-catalog")
                .join("catalog"),
            yaml_style: Some(validation.join("..").join(".ryl.toml")),
        }
    }

    /// The built directory.
    pub fn built(&self) -> PathBuf {
        self.target.join("catalog")
    }
}

/// How a build treats the cache.
#[derive(Clone, Debug, Default)]
pub struct BuildOptions {
    /// Layers built from the remotes again, by name, whatever the cache
    /// holds; every layer when `all` is set.
    pub fresh: Vec<String>,

    /// Build every layer from the remotes again.
    pub all: bool,

    /// Fetch every file built from the remotes, and check it hashes to its
    /// pin.
    pub verify_remote: bool,
}

/// The base layer's `$contracts`: the compiled kits' contracts.
fn kit_contracts() -> Result<OrderedNode, String> {
    contracts_section(&kit_catalog_contracts()).map_err(|e| e.to_string())
}

/// A layer's cache key: the builder's version, the source, and, for the
/// base layer, the contracts it is given.
fn cache_key(
    source_text: &str,
    contracts: Option<&str>,
) -> String {
    let mut keyed = format!("{TOOL_STAMP}\n{source_text}");
    if let Some(contracts) = contracts {
        keyed.push_str("\n$contracts\n");
        keyed.push_str(contracts);
    }
    sha256_of(keyed.as_bytes())
}

/// Builds every layer the sources' manifest lists, from the cache where it
/// holds a layer's key, and checks they import as one stack.
///
/// # Errors
/// A source that doesn't read or build, or a stack that refuses a layer.
pub fn build(
    remote: &dyn Remote,
    paths: &Paths,
    options: &BuildOptions,
) -> Result<BuiltCatalog, String> {
    let manifest_path = paths.sources.join(MANIFEST);
    let manifest = parse_manifest(
        &fs::read_to_string(&manifest_path)
            .map_err(|e| format!("read {}: {e}", manifest_path.display()))?,
    )
    .map_err(|e| format!("{}: {e}", manifest_path.display()))?;
    for name in &options.fresh {
        if !manifest.iter().any(|e| e.name() == name) {
            let names: Vec<_> = manifest.iter().map(ManifestEntry::name).collect();
            return Err(format!(
                "no layer `{name}`; the layers are {}",
                names.join(", ")
            ));
        }
    }

    let style = match &paths.yaml_style {
        Some(path) => Some(
            ryl::config::YamlLintConfig::from_toml_str(
                &fs::read_to_string(path).map_err(|e| format!("read {}: {e}", path.display()))?,
            )
            .map_err(|e| format!("{}: {e}", path.display()))?,
        ),
        None => None,
    };
    let contracts = kit_contracts()?;
    let contracts_text = contracts.to_yaml().map_err(|e| e.to_string())?;
    let cache = paths.target.join("layers");
    let mut layers = Vec::new();
    let mut stack = BunsenCatalogStack::new();
    for (i, entry) in manifest.iter().enumerate() {
        let source_path = paths.sources.join(&entry.file);
        let source_text = fs::read_to_string(&source_path)
            .map_err(|e| format!("read {}: {e}", source_path.display()))?;
        let base = i == 0;
        let key = cache_key(&source_text, base.then_some(contracts_text.as_str()));
        let cached = cache.join(format!("{}-{}.yml", entry.name(), &key[..16]));
        let fresh = options.all || options.fresh.iter().any(|f| f == entry.name());
        let text = if cached.exists() && !fresh {
            fs::read_to_string(&cached).map_err(|e| format!("read {}: {e}", cached.display()))?
        } else {
            eprintln!("building {}", entry.file);
            let text = build_layer(
                remote,
                &source_text,
                base.then(|| contracts.clone()),
                options.verify_remote,
            )
            .map_err(|e| format!("{}: {e}", source_path.display()))?;
            fs::create_dir_all(&cache).map_err(|e| format!("{}: {e}", cache.display()))?;
            fs::write(&cached, &text).map_err(|e| format!("{}: {e}", cached.display()))?;
            text
        };
        let text = match &style {
            Some(style) => ryl::format::format_str(&text, style, Path::new(&entry.file), &[]),
            None => text,
        };
        stack.push_yaml(entry.name(), &text).map_err(|e| {
            format!(
                "{}: the built layer doesn't import:\n{}",
                entry.file,
                e.problem_lines()
            )
        })?;
        layers.push(text);
    }
    Ok(BuiltCatalog { manifest, layers })
}

/// Builds one layer's text from its source.
///
/// # Errors
/// As [`LayerBuilder::build`], and a result that isn't a catalog.
pub fn build_layer(
    remote: &dyn Remote,
    source_text: &str,
    contracts: Option<OrderedNode>,
    verify_remote: bool,
) -> Result<String, String> {
    let source = OrderedNode::from_yaml(source_text).map_err(|e| e.to_string())?;
    let built = LayerBuilder::new(remote, verify_remote).build(source, contracts)?;
    let catalog = BunsenCatalog::from_node(built).map_err(|e| e.to_string())?;
    let mut text = String::from(
        "# Generated by `cargo catalog update` from its probe-contract source; don't edit by hand.\n",
    );
    text.push_str(&catalog.to_node().to_yaml().map_err(|e| e.to_string())?);
    if !text.ends_with('\n') {
        text.push('\n');
    }
    Ok(text)
}

/// Writes `catalog` as the directory `dir`, replacing what was there.
///
/// # Errors
/// What the filesystem refuses.
pub fn write_dir(
    catalog: &BuiltCatalog,
    dir: &Path,
) -> Result<(), String> {
    if dir.exists() {
        fs::remove_dir_all(dir).map_err(|e| format!("remove {}: {e}", dir.display()))?;
    }
    fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for (name, text) in catalog.files() {
        let path = dir.join(&name);
        fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    Ok(())
}

/// The files of `dir` that differ from `catalog`'s: changed, missing from
/// `dir`, or in `dir` but not the catalog's.
///
/// # Errors
/// A directory that can't be read.
pub fn differences(
    catalog: &BuiltCatalog,
    dir: &Path,
) -> Result<Vec<String>, String> {
    let mut differ = Vec::new();
    let files = catalog.files();
    for (name, text) in &files {
        match fs::read_to_string(dir.join(name)) {
            Ok(current) if &current == text => {}
            Ok(_) => differ.push(format!("{name}: changed")),
            Err(_) => differ.push(format!("{name}: missing")),
        }
    }
    if dir.exists() {
        let read = fs::read_dir(dir).map_err(|e| format!("read {}: {e}", dir.display()))?;
        let mut extra: Vec<String> = read
            .filter_map(|e| e.ok())
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .filter(|name| !files.iter().any(|(f, _)| f == name))
            .map(|name| format!("{name}: not in the build"))
            .collect();
        extra.sort();
        differ.extend(extra);
    }
    Ok(differ)
}

#[cfg(test)]
mod tests {
    use bunsen::data::resources::hub::HubRepo;

    use super::*;
    use crate::remote::testing::FakeRemote;

    const PRELUDE: &str = r#"
$description: "The vocabulary."
publisher: { $kind: facet, $description: "Who publishes it." }
family: { $kind: facet, $description: "A line of architectures." }
template_class_root:
  $kind: template_class
  $description: "The root."
  $required_facets: [publisher, family]
"#;

    const QWEN: &str = r#"
qwen:
  $kind: namespace
  $facet: publisher
  $description: "Qwen."
  qwen3:
    $kind: namespace
    $facet: family
    $description: "Qwen3."
    m:
      $kind: build
      $description: "M."
      $contract: qwen3-lm
      $hub: { $repo: o/m, $revision: abc }
      $resources: { checkpoint: checkpoint, config: config, tokenizer: tokenizer, tokenizer_config: tokenizer_config, generation_config: generation_config }
      checkpoint: { $kind: resource, $file: model.safetensors, $format: safetensors }
      config: { $kind: resource, $file: config.json, $format: json }
      tokenizer: { $kind: resource, $file: tokenizer.json, $format: tokenizer.json }
      tokenizer_config: { $kind: resource, $file: tokenizer_config.json, $format: tokenizer_config.json }
      generation_config: { $kind: resource, $file: generation_config.json, $format: generation_config.json }
"#;

    fn fake() -> FakeRemote {
        FakeRemote::default().with_repo(
            &HubRepo {
                repo: "o/m".into(),
                revision: "abc".into(),
            },
            &[
                ("config.json", br#"{"torch_dtype": "bfloat16"}"#),
                ("tokenizer.json", b"{}"),
                ("tokenizer_config.json", b"{}"),
                ("generation_config.json", b"{}"),
            ],
            &[("model.safetensors", b"weights")],
        )
    }

    /// A scratch directory under the validation workspace's target.
    fn scratch(name: &str) -> PathBuf {
        let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../target/catalog-builder-tests")
            .join(name);
        if dir.exists() {
            fs::remove_dir_all(&dir).unwrap();
        }
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    /// The sources build into a catalog whose base layer carries the kits'
    /// contracts and whose layers import as one stack; a second build reads
    /// the cache alone; the checked-in directory differs until it is
    /// written, and a layer it doesn't list is a difference.
    #[test]
    fn test_build_check_update() {
        let dir = scratch("build");
        let paths = Paths {
            sources: dir.join("sources"),
            target: dir.join("target"),
            checked_in: dir.join("checked-in"),
            yaml_style: None,
        };
        fs::create_dir_all(&paths.sources).unwrap();
        fs::write(
            paths.sources.join(MANIFEST),
            "prelude.yml\nqwen3.yml kits\n",
        )
        .unwrap();
        fs::write(paths.sources.join("prelude.yml"), PRELUDE).unwrap();
        fs::write(paths.sources.join("qwen3.yml"), QWEN).unwrap();

        let remote = fake();
        let built = build(&remote, &paths, &BuildOptions::default()).unwrap();
        assert!(built.layers[0].contains("qwen3-lm:"), "{}", built.layers[0]);
        assert!(built.layers[1].contains("bfloat16"), "{}", built.layers[1]);
        assert!(remote.requests.get() > 0);

        let cached = fake();
        assert_eq!(
            build(&cached, &paths, &BuildOptions::default()).unwrap(),
            built
        );
        assert_eq!(cached.requests.get(), 0);

        assert_eq!(
            differences(&built, &paths.checked_in).unwrap(),
            [
                "MANIFEST.txt: missing",
                "prelude.yml: missing",
                "qwen3.yml: missing"
            ]
        );
        write_dir(&built, &paths.checked_in).unwrap();
        assert!(differences(&built, &paths.checked_in).unwrap().is_empty());
        fs::write(paths.checked_in.join("stale.yml"), "").unwrap();
        assert_eq!(
            differences(&built, &paths.checked_in).unwrap(),
            ["stale.yml: not in the build"]
        );

        let fresh = fake();
        let options = BuildOptions {
            fresh: vec!["qwen3".into()],
            ..BuildOptions::default()
        };
        assert_eq!(build(&fresh, &paths, &options).unwrap(), built);
        assert!(fresh.requests.get() > 0);
        let unknown = BuildOptions {
            fresh: vec!["qwen9".into()],
            ..BuildOptions::default()
        };
        assert!(
            build(&fresh, &paths, &unknown)
                .unwrap_err()
                .contains("no layer `qwen9`")
        );
    }

    #[test]
    fn test_manifest_round_trip() {
        let manifest = parse_manifest(
            "# the layers\nprelude.yml\ncommons.yml   # shared\nqwen3.yml kits\n\nwhisper.yml speech\n",
        )
        .unwrap();
        assert_eq!(
            manifest.iter().map(ManifestEntry::name).collect::<Vec<_>>(),
            ["prelude", "commons", "qwen3", "whisper"]
        );
        assert_eq!(manifest[2].feature.as_deref(), Some("kits"));
        assert_eq!(
            parse_manifest(&render_manifest(&manifest)).unwrap(),
            manifest
        );
    }

    #[test]
    fn test_manifest_refusals() {
        assert!(parse_manifest("a.yml b c").unwrap_err().contains("line 1"));
        assert!(
            parse_manifest("a.yml\na.yml")
                .unwrap_err()
                .contains("twice")
        );
        assert!(
            parse_manifest("# nothing\n")
                .unwrap_err()
                .contains("no layers")
        );
    }

    #[test]
    fn test_cache_key_follows_the_source_and_contracts() {
        assert_eq!(cache_key("a", None), cache_key("a", None));
        assert_ne!(cache_key("a", None), cache_key("b", None));
        assert_ne!(cache_key("a", None), cache_key("a", Some("c")));
    }
}
